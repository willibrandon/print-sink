namespace PrintSink.Core.Capabilities;

/// <summary>
/// Defines XML namespace URIs used by Print Device Capabilities documents.
/// </summary>
public static class PrintSchemaNamespaces
{
    /// <summary>
    /// The Print Schema Framework v2 namespace.
    /// </summary>
    public const string Framework2 = "http://schemas.microsoft.com/windows/2013/12/printing/printschemaframework2";

    /// <summary>
    /// The Print Schema Keywords namespace.
    /// </summary>
    public const string Keywords = "http://schemas.microsoft.com/windows/2003/08/printing/printschemakeywords";

    /// <summary>
    /// The Print Schema Keywords v1.2 namespace.
    /// </summary>
    public const string Keywords12 = "http://schemas.microsoft.com/windows/2013/12/printing/printschemakeywordsv12";

    /// <summary>
    /// The XML Schema namespace.
    /// </summary>
    public const string XmlSchema = "http://www.w3.org/2001/XMLSchema";

    /// <summary>
    /// The XML Schema instance namespace.
    /// </summary>
    public const string XmlSchemaInstance = "http://www.w3.org/2001/XMLSchema-instance";
}
